/**
 * W3 — Verifiable provenance: a desktop capsule in the browser.
 *
 * Continues the DataLab desktop showcase (scenario D2): the capsule it
 * exports (``public/demos/showcase-capsule.dlcapsule``, generated by
 * ``scripts/gen_showcase_capsule.py``: a noisy image of cells, total
 * variation denoising, Sobel edges and blob detection) is inspected from
 * the File menu (intact), opened (images and provenance restored, shown in
 * the Provenance tab), replayed locally (every step exact), then reviewed:
 * the review cites the replay report and is checked against the capsule.
 *
 * The native file pickers are answered in the page with the bundled
 * capsule, the report and the review (see ``answerFilePicker``), and the
 * saves are captured in the page (see ``captureSave``): no native dialog
 * opens and nothing is downloaded. The capsule revision recorded by the
 * inspection is forgotten at the end. Needs DataLab-Capsule in the Python
 * runtime: skipped otherwise.
 */

const DEMO_CAPSULE = "demos/showcase-capsule.dlcapsule";
/** Blobs (cells) detected on the denoised image of the capsule. */
const CELLS_COUNT = 14;
/** Operations recorded in the capsule, in order. */
const OPERATIONS = [
  "sigima.image.denoise_tv",
  "sigima.image.sobel",
  "sigima.image.blob_log",
];
/** Python calls of the capsule (inspection, opening, replay, review). */
const TASK_TIMEOUT_MS = 60_000;

const IMAGE_HOST = ".image-plot-host";
const PROVENANCE_PANEL = '[data-testid="provenance-panel"]';

function text(el: Element | null | undefined): string {
  return (el?.textContent ?? "").replace(/\s+/g, " ").trim();
}

/** Click a panel tab once enabled (tabs are disabled while busy). */
async function clickEnabledTab(
  ctx: ShowcaseContext,
  name: string,
): Promise<void> {
  const tab = await ctx.waitFor(
    () => {
      const el = ctx.tab(name);
      return el && !(el as HTMLButtonElement).disabled ? el : null;
    },
    30_000,
    `the ${name} tab to be enabled`,
  );
  await ctx.click(tab);
}

/** Object tree row whose title contains ``part``. */
function treeItem(ctx: ShowcaseContext, part: string): HTMLElement | null {
  return (
    ctx
      .$$(".object-tree-item")
      .find((item) =>
        text(item.querySelector(".object-tree-title")).includes(part),
      ) ?? null
  );
}

/** Select a tree row by its second line: the title may hold links to
 *  other objects (short IDs), which select them when clicked. */
async function selectTreeItem(
  ctx: ShowcaseContext,
  part: string,
): Promise<void> {
  const item = await ctx.find(() => treeItem(ctx, part), 15_000);
  await ctx.click(item.querySelector<HTMLElement>(".object-tree-meta") ?? item);
  await ctx.waitFor(
    () => treeItem(ctx, part)?.classList.contains("selected"),
    5_000,
    `"${part}" to be selected`,
  );
}

/** Open the Workspace capsule dialog from the File menu, on ``tab``. */
async function openCapsuleDialog(
  ctx: ShowcaseContext,
  tab: string,
): Promise<void> {
  await ctx.clickMenuPath("File", "file.capsule");
  await ctx.waitFor(CAPSULE_DIALOG, 15_000);
  await ctx.hold(500);
  await ctx.clickTab(tab);
}

/** Choose the capsule in the Inspect tab and wait for its inspection. */
async function inspectCapsule(
  ctx: ShowcaseContext,
  capsule: File,
): Promise<void> {
  await answerFilePicker(ctx, capsule, () =>
    ctx.click(capsuleTestId("capsule-choose")),
  );
  await ctx.checkpoint(
    () =>
      text(ctx.$(capsuleTestId("capsule-integrity-status"))) === t("Intact"),
    "the capsule is inspected: intact",
    TASK_TIMEOUT_MS,
  );
}

/** Spotlight ``selector`` (scrolled into view) while a caption is read. */
async function showWhile(
  ctx: ShowcaseContext,
  selector: string,
  caption: string,
  holdMs: number,
  position: "top" | "bottom" = "bottom",
): Promise<void> {
  const el = await ctx.find(selector, 10_000);
  await reveal(ctx, el);
  await ctx.spotlight(el, 6);
  await ctx.say(caption, holdMs, { position });
  ctx.clearSpotlight();
}

/** 1. The capsule, inspected from the File menu: intact. */
async function inspectStep(ctx: ShowcaseContext, capsule: File): Promise<void> {
  await ctx.say(t("Every result keeps track of how it was computed."), 2200);
  await ctx.say(
    t(
      "This capsule was exported by DataLab desktop: a workspace with the full provenance of its processing.",
    ),
    3200,
  );
  await ctx.say(t("Open it from the File menu, right in the browser."), 1000);
  await openCapsuleDialog(ctx, "Inspect");
  await ctx.say(
    t("Inspect it first: the files are checked, nothing is executed."),
    1400,
    { position: "top" },
  );
  await inspectCapsule(ctx, capsule);
  await ctx.checkpoint(
    () =>
      ctx.$$(`${capsuleTestId("capsule-activities")} tbody tr`).length ===
      OPERATIONS.length,
    "the capsule records three activities",
    5_000,
  );
  await showWhile(
    ctx,
    capsuleTestId("capsule-summary"),
    t(
      "Produced by DataLab desktop: three recorded steps (denoising, edges, blob detection), each one replayable.",
    ),
    4800,
  );
  await showWhile(
    ctx,
    capsuleTestId("capsule-integrity"),
    t(
      "Intact: every file matches its SHA-256 fingerprint, nothing was altered.",
    ),
    4200,
    "top",
  );
}

/** 2. Opened as the workspace: the image chain and its provenance. */
async function openStep(ctx: ShowcaseContext): Promise<void> {
  await ctx.say(
    t("Open it as the workspace: the images come back with their provenance."),
    1500,
    { position: "top" },
  );
  await ctx.click(capsuleTestId("capsule-open"));
  await ctx.checkpoint(
    async () => (await ctx.host.runtime.listImages()).length === 3,
    "the capsule is opened: three images",
    TASK_TIMEOUT_MS,
  );
  const images = await ctx.host.runtime.listImages();
  const denoised = images.find((image) => image.title.includes("denoise_tv"));
  if (!denoised) throw new Error("No denoised image in the capsule");
  await ctx.checkpoint(
    async () =>
      (await ctx.host.runtime.listImageResults(denoised.id)).some(
        (result) =>
          result.category === "geometry" &&
          result.func_name === "blob_log" &&
          result.coords.length === CELLS_COUNT,
      ),
    `the ${CELLS_COUNT} blobs are restored on the denoised image`,
    10_000,
  );
  await ctx.hold(600);
  await closeCapsuleDialog(ctx);

  await clickEnabledTab(ctx, "Images");
  await selectTreeItem(ctx, "Cells");
  await waitForStablePlot(ctx, IMAGE_HOST, 15_000);
  await ctx.say(t("The raw image of cells…"), 1800);
  await selectTreeItem(ctx, "sobel");
  await waitForStablePlot(ctx, IMAGE_HOST, 15_000);
  await ctx.say(t("…its edges…"), 1600);
  await selectTreeItem(ctx, "denoise_tv");
  await waitForStablePlot(ctx, IMAGE_HOST, 15_000);
  await ctx.spotlight("main.plot-area", 4);
  await ctx.say(
    t("…and the {count} cells detected on the denoised image.", {
      count: CELLS_COUNT,
    }),
    3200,
  );
  ctx.clearSpotlight();

  await clickEnabledTab(ctx, "Provenance");
  await ctx.checkpoint(
    () => text(ctx.visible(PROVENANCE_PANEL)).includes(OPERATIONS[0]),
    "the Provenance tab shows the denoising",
    TASK_TIMEOUT_MS,
  );
  await showWhile(
    ctx,
    `${PROVENANCE_PANEL} .provenance-section`,
    t(
      "The Provenance tab: operation, parameters and input, as recorded by DataLab desktop.",
    ),
    4500,
  );
  const analyses = `${PROVENANCE_PANEL} [data-testid="provenance-analyses"]`;
  await ctx.click(`${analyses} > summary`);
  await ctx.checkpoint(
    () => {
      const details = ctx.$<HTMLDetailsElement>(analyses);
      return details?.open && text(details).includes(OPERATIONS[2]);
    },
    "the blob detection is recorded on the denoised image",
    5_000,
  );
  await showWhile(
    ctx,
    analyses,
    t("The blob detection is recorded too, with its own parameters."),
    4000,
  );
}

/** Replay button of ``row``, once enabled (one replay at a time). */
function replayButton(row: Element): HTMLButtonElement | null {
  const button = row.querySelector<HTMLButtonElement>(
    '[data-testid="capsule-replay-button"]',
  );
  return button && !button.disabled && isVisible(button) ? button : null;
}

/** 3. Every step replayed in this browser: exact. Returns the report of
 *  the blob detection. */
async function replayStep(ctx: ShowcaseContext): Promise<File> {
  await openCapsuleDialog(ctx, "Local replay");
  const rows = await ctx.waitFor(
    () => {
      const found = ctx.$$(capsuleTestId("capsule-replay-row"));
      return found.length === OPERATIONS.length ? found : null;
    },
    15_000,
    "the activities of the workspace",
  );
  await ctx.say(
    t(
      "Local replay: each step is recomputed in this browser and compared with the result stored by DataLab desktop.",
    ),
    3200,
    { position: "top" },
  );
  for (const row of rows) {
    await ctx.click(
      await ctx.waitFor(() => replayButton(row), TASK_TIMEOUT_MS),
    );
    const verdict = () =>
      text(row.querySelector('[data-testid="capsule-replay-verdict"]'));
    await ctx.checkpoint(
      () => verdict() !== "",
      "the activity is replayed",
      TASK_TIMEOUT_MS,
    );
    await ctx.checkpoint(
      () => verdict().startsWith(t("Exact")),
      `the replay of ${text(row.querySelectorAll("td")[1])} is exact (${verdict()})`,
    );
    await ctx.hold(500);
  }
  await showWhile(
    ctx,
    `${capsuleTestId("capsule-replay")} .capsule-table`,
    t(
      "Exact: bit-for-bit identical to the results computed by DataLab desktop.",
    ),
    4200,
    "top",
  );
  const blobRow = rows[rows.length - 1];
  await ctx.say(
    t("The verification is saved as a report, to be cited."),
    1500,
    { position: "top" },
  );
  const report = await captureSave(ctx, () =>
    ctx.click(() =>
      blobRow.querySelector<HTMLElement>('[data-testid="capsule-save-report"]'),
    ),
  );
  await ctx.checkpoint(async () => {
    const content = JSON.parse(await report.text()) as { verdict?: string };
    return content.verdict === "exact";
  }, "the replay report of the blob detection is saved (exact)");
  return report;
}

/** 4. A review of the capsule, citing the report, checked against it. */
async function reviewStep(
  ctx: ShowcaseContext,
  capsule: File,
  report: File,
): Promise<void> {
  await ctx.clickTab("Inspect");
  await ctx.say(t("Anyone can now review the capsule."), 1200, {
    position: "top",
  });
  await inspectCapsule(ctx, capsule);
  const fingerprint = text(
    ctx.$(`${capsuleTestId("capsule-summary")} .capsule-facts dd code`),
  );
  await ctx.checkpoint(
    fingerprint.startsWith("sha256:"),
    "the fingerprint of the capsule is shown",
  );
  const reviewer = t("Booth visitor");
  await ctx.type(capsuleTestId("capsule-reviewer"), reviewer);
  await ctx.type(
    capsuleTestId("capsule-statement"),
    t("Replayed in my browser: every step is exact."),
  );
  await ctx.select(capsuleTestId("capsule-verdict"), "endorsed");
  await answerFilePicker(ctx, report, () =>
    ctx.click(capsuleTestId("capsule-cite-report")),
  );
  const writer = capsuleTestId("capsule-review-writer");
  await ctx.checkpoint(
    () =>
      text(ctx.$(writer)).includes(t("Cited reports: {count}", { count: 1 })),
    "the review cites the replay report",
    10_000,
  );
  await showWhile(
    ctx,
    writer,
    t(
      "The review endorses the capsule and cites the replay report as evidence.",
    ),
    3500,
    "top",
  );
  const review = await captureSave(ctx, () =>
    ctx.click(capsuleTestId("capsule-write-review")),
  );
  await ctx.checkpoint(async () => {
    const content = JSON.parse(await review.text()) as {
      target?: string;
      reviewer?: { name?: string };
      reports?: unknown[];
    };
    return (
      content.reviewer?.name === reviewer &&
      content.reports?.length === 1 &&
      content.target === fingerprint
    );
  }, "the review of this capsule is written, citing the report");
  await ctx.say(
    t("The review is a separate file: the capsule itself is never changed."),
    2800,
  );
  await answerFilePicker(ctx, review, () =>
    ctx.click(capsuleTestId("capsule-add-review")),
  );
  await ctx.checkpoint(
    () =>
      text(ctx.$(capsuleTestId("capsule-review-status"))).includes(
        t("consistent"),
      ),
    "the review is checked against the capsule: consistent",
    TASK_TIMEOUT_MS,
  );
  await showWhile(
    ctx,
    capsuleTestId("capsule-documents"),
    t(
      "Checked against this exact capsule: consistent. A traceable, verifiable validation.",
    ),
    4500,
    "top",
  );
  await closeCapsuleDialog(ctx);
}

export const w3Capsule: ShowcaseScenario = {
  id: "w3",
  title: () => t("Verifiable provenance: a desktop capsule in the browser"),
  subtitle: () =>
    t("Open and verify a DataLab desktop capsule, without installing anything"),
  async run(ctx) {
    const info = await ctx.host.runtime.getProvenanceLedger();
    if (!info.available) {
      throw new ScenarioSkipped(
        "provenance is not available (DataLab-Capsule is not installed)",
      );
    }
    const capsule = await demoFile(DEMO_CAPSULE);
    const restoreRevisions = await guardRevisions();
    try {
      await inspectStep(ctx, capsule);
      await openStep(ctx);
      const report = await replayStep(ctx);
      await reviewStep(ctx, capsule, report);
      await ctx.spotlight("main.plot-area", 4);
      await ctx.say(
        t("Provenance travels with the data, from desktop to browser."),
        3500,
      );
      ctx.clearSpotlight();
    } finally {
      ctx.clearSpotlight();
      await forceCloseCapsuleDialog();
      await restoreRevisions();
    }
  },
};
